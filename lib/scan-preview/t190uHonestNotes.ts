function norm(name: string): string {
  return name.trim().toLowerCase().replace(/\s+/g, ' ');
}

function capFirst(name: string): string {
  const text = name.trim();
  return text.charAt(0).toUpperCase() + text.slice(1);
}

/** gummy, lozenge, or chew. Soft chew is chew. */
export function t190uFormWord(form: string | undefined): 'gummy' | 'lozenge' | 'chew' | null {
  const value = (form ?? '').trim().toLowerCase();
  if (value === 'gummy') return 'gummy';
  if (value === 'lozenge') return 'lozenge';
  if (value === 'chew' || value === 'soft chew') return 'chew';
  return null;
}

function limitedTokens(ingredients: readonly IngredientFlag[]): string[] {
  const seen = new Set<string>();
  const printed: string[] = [];
  for (const ingredient of ingredients) {
    if (!ingredientCountsTowardLimitedStack(ingredient)) continue;
    const key = norm(ingredient.name);
    if (seen.has(key)) continue;
    seen.add(key);
    printed.push(ingredient.name.trim());
  }
  return printed;
}

function formOils(ingredients: readonly IngredientFlag[]): IngredientFlag[] {
  const seen = new Set<string>();
  const oils: IngredientFlag[] = [];
  for (const ingredient of ingredients) {
    const key = norm(ingredient.name);
    if (!FORM_OIL.has(key) || seen.has(key)) continue;
    seen.add(key);
    oils.push(ingredient);
  }
  return oils;
}

export function stackingHonestNote(tokens: readonly string[]): string {
  return `Although this product does not contain any Avoid ingredients, it has ${tokens.length} Limited ingredients: ${tokens.join(', ')}. Under our rules, three or more Limited ingredients downgrade a product from Caution to Avoid.`;
}

export function contradictionHonestNoteForOil(oil: string, form: 'gummy' | 'lozenge' | 'chew'): string {
  return `${capFirst(oil)} is graded Avoid here because it is the base of this ${form}. In that form the oil is a primary ingredient you consume directly. The same oil is graded Cleared when it is only the fill of a capsule or softgel, because there it functions as a carrier rather than the main edible base.`;
}

export type T190uDecision =
  | { kind: 'skip' }
  | { kind: 'write'; template: 'stacking' | 'contradiction'; note: string }
  | { kind: 'hold'; reasons: Array<'a-not-Avoid' | 'a-has-Avoid-token' | 'b-not-Avoid-form'>; detail: string };

export function t190uDecision(record: RatingRecord): T190uDecision {
  const role = ROLE[record.id];
  if (!role) return { kind: 'skip' };
  const ingredients = record.inactiveIngredients ?? [];
  if (role === 'stacking' || role === 'both') {
    const reasons: Array<'a-not-Avoid' | 'a-has-Avoid-token'> = [];
    if (record.verdict !== 'avoid') reasons.push('a-not-Avoid');
    const avoidTokens = ingredients.filter((ingredient) => ingredient.riskLevel === 'high').map((ingredient) => ingredient.name.trim());
    if (avoidTokens.length > 0) reasons.push('a-has-Avoid-token');
    if (reasons.length > 0) {
      const detail = reasons.includes('a-has-Avoid-token') ? avoidTokens.join(', ') : record.verdict;
      return { kind: 'hold', reasons, detail };
    }
    const tokens = limitedTokens(ingredients);
    if (tokens.length < 3) return { kind: 'hold', reasons: ['a-not-Avoid'], detail: `only ${tokens.length} Limited` };
    return { kind: 'write', template: 'stacking', note: stackingHonestNote(tokens) };
  }
  const form = t190uFormWord(record.form);
  const oils = formOils(ingredients);
  const avoidOils = oils.filter((ingredient) => ingredient.riskLevel === 'high');
  if (!form || oils.length === 0 || avoidOils.length !== oils.length) {
    const detail = oils.map((ingredient) => `${ingredient.name.trim()} ${ingredient.riskLevel} ${(record.form ?? '').trim()}`).join('; ') || (record.form ?? '');
    return { kind: 'hold', reasons: ['b-not-Avoid-form'], detail };
  }
  const note = avoidOils.map((ingredient) => contradictionHonestNoteForOil(ingredient.name, form)).join(' ');
  return { kind: 'write', template: 'contradiction', note };
}

/** Sets the honest note only. Grades, why text, and every other field stay as they are. */
export function applyT190uHonestNote(record: RatingRecord): RatingRecord {
  const decision = t190uDecision(record);
  if (decision.kind !== 'write') return record;
  if (record.honestNote === decision.note && record.founderHonestNote === decision.note) return record;
  return { ...record, honestNote: decision.note, founderHonestNote: decision.note };
}

