type RowIn = {
  id: string;
  productName: string;
  category: string;
  formulaId: string;
  audience: typeof ADULT | typeof KIDS;
  minAge: number;
  form: string;
  productType: typeof VITAMIN | typeof SUPPLEMENT | typeof OTC;
  productSubtype?: string;
  barcode?: string;
  actives: RatingRecord['activeIngredients'];
  inactives: IngredientFlag[];
  verdict: RatingRecord['verdict'];
  note: string;
  cite: string;
  alts?: CleanAlternative[];
  homeo?: boolean;
  zinc?: boolean;
  iron?: boolean;
  prenatal?: boolean;
};

function row(d: RowIn): RatingRecord {
  const homeo = d.homeo || d.productSubtype === 'homeopathic';
  return {
    id: d.id,
    productName: d.productName,
    brand: BRAND,
    category: d.category,
    ...(d.barcode ? { barcode: d.barcode } : {}),
    formulaId: d.formulaId,
    audience: d.audience,
    minAge: d.minAge,
    form: d.form,
    recordStatus: UNVERIFIED,
    productType: d.productType,
    ...(d.productSubtype && d.productSubtype !== 'None'
      ? { productSubtype: d.productSubtype }
      : {}),
    ...(homeo ? { homeopathicSubtype: 'homeopathic' } : {}),
    activeIngredients: d.actives,
    inactiveIngredients: d.inactives,
    verdict: d.verdict,
    honestNote: `${d.note} ${LIMITED_STACK}${
      d.zinc ? ' ' + ZINC_PARKED : ''
    }${d.iron ? ' ' + IRON_OVERDOSE : ''}${
      d.prenatal ? ' ' + PRENATAL_LABEL : ''
    }${homeo ? ' ' + CARLSTON : ''} Pack sizes of the same name+form+inactives share formulaId. Draft, not verified.`.replace(/\s+/g, ' ').trim(),
    retailers: [...RETAILERS],
    cleanAlternatives: d.verdict === 'clean' ? undefined : d.alts,
    sourcesGeneral: [`${d.cite} — ${UNVERIFIED_NOTE}`, ...(homeo ? [CARLSTON] : [])],
  };
}

